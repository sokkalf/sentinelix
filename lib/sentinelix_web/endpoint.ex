defmodule SentinelixWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :sentinelix

  # The session is stored in a signed and encrypted cookie. It only holds a
  # random session token; the token row in `users_tokens` is what makes the
  # session valid (see SentinelixWeb.UserAuth), so sessions can be revoked.
  # `same_site: "Lax"` is required for the OIDC callback (a top-level GET
  # navigation from the IdP) to receive the cookie. `max_age` matches the
  # session token validity in Sentinelix.Accounts.UserToken.
  @session_options [
    store: :cookie,
    key: "_sentinelix_key",
    signing_salt: "kRX3GPAB",
    encryption_salt: "6N8iz0V0",
    same_site: "Lax",
    max_age: 14 * 24 * 60 * 60
  ]

  # Peer data and x-headers give wall displays (SentinelixWeb.WallLive)
  # the client address for rate limiting, see SentinelixWeb.Plugs.ClientIP.
  @connect_info [:peer_data, :x_headers, session: @session_options]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: @connect_info],
    longpoll: [connect_info: @connect_info]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :sentinelix,
    gzip: not code_reloading?,
    only: SentinelixWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :sentinelix
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  # Real client address behind a trusted reverse proxy (TRUSTED_PROXIES).
  plug SentinelixWeb.Plugs.ClientIP

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint], log: {__MODULE__, :log_level, []}

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug SentinelixWeb.Router

  @doc """
  The level of the request log lines: none for wall displays, whose path
  holds their token (`SentinelixWeb.WallAuth` logs them without it).
  """
  @spec log_level(Plug.Conn.t()) :: Logger.level() | false
  def log_level(%Plug.Conn{path_info: ["wall" | _]}), do: false
  def log_level(_conn), do: :info
end
